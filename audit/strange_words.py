ALLOWLIST_N = {_norm(x) for x in ALLOWLIST}


def zipf(word: str) -> float:
    """Максимум частоты по поверхностной форме и лемме."""
    z = wordfreq.zipf_frequency(word, "ru")
    p = morph.parse(word)
    if p:
        z = max(z, wordfreq.zipf_frequency(p[0].normal_form, "ru"))
    return z


def is_merge(word: str) -> bool:
    """True, если слово — артефакт склейки дампа (заголовок прилип к тексту)."""
    # (1) заглавная буква внутри слова — верный признак склейки «облакоГлавный»
    if re.search(r"[а-яё][А-ЯЁ]", word):
        return True
    # (2) режется на два обычных русских слова (склейка двух строчных)
    lw = word.lower()
    for i in range(MIN_LEN - 1, len(lw) - (MIN_LEN - 2)):
        a, b = lw[:i], lw[i:]
        if zipf(a) >= SPLIT_MIN_ZIPF and zipf(b) >= SPLIT_MIN_ZIPF:
            return True
    return False


def is_proper(word: str) -> bool:
    if word in KNOWN_NAMES:
        return True
    tags = str(morph.parse(word)[0].tag)
    return any(g in tags for g in ("Name", "Surn", "Patr", "Geox", "Orgn", "Trad"))


def lemma(word: str) -> str:
    return morph.parse(word)[0].normal_form


def split_essays(text: str):
    blocks = re.split(r"(?m)^=== ", text)
    out = {}
    for b in blocks:
        if " · " not in b:
            continue
        slug = b.split(" · ")[0].strip()
        body = re.sub(r"^.*?===", "", b, count=1, flags=re.S)
        out[slug] = body
    return out


def context(body: str, word: str, w: int = 55) -> str:
    m = re.search(re.escape(word), body)
    if not m:
        return ""
    s, e = max(0, m.start() - w), min(len(body), m.end() + w)
    return "…" + body[s:e].replace("\n", " ").strip() + "…"


def scan_mixed(name, body):
    """Детектор 2: латинская буква внутри кириллического слова (Менгoли, дuмаешь)."""
    out = []
    for m in re.finditer(r"[A-Za-zА-Яа-яёЁ]+", body):
        w = m.group(0)
        if (re.search(r"[а-яё]", w, re.I) and re.search(r"[A-Za-z]", w)
                and re.search(r"[а-яё][A-Za-z]|[A-Za-z][а-яё]", w, re.I) and len(w) >= 3):
            out.append((name, w, context(body, w)))
    return out


def scan_stop(name, body):
    """Детектор 3: забракованные реальные слова (стоп-лист) с исключениями."""
    out = []
    low = body.lower()
    for pat, label in STOP_TERMS:
        for m in re.finditer(pat, low):
            hit = m.group(0)
            if hit in STOP_ALLOW:
                continue
            if (name, label.rstrip("*")) in STOP_ALLOW_NODE:
                continue
            out.append((name, label, context(body, hit)))
    return out


def load_bodies(path):
    """{name: body}. path — дамп .md (эссе) ИЛИ папка с .html (объекты)."""
    import os
    if os.path.isdir(path):
        out = {}
        for root, _, files in os.walk(path):
            for f in files:
                if not f.endswith(".html"):
                    continue
                h = open(os.path.join(root, f), encoding="utf-8", errors="ignore").read()
                h = re.sub(r"<(script|style|head).*?</\1>", " ", h, flags=re.S)
                h = re.sub(r"<[^>]+>", " ", h)
                h = re.sub(r"&[a-z]+;", " ", h)
                out[f[:-5]] = re.sub(r"\s+", " ", h)
        return out
    return split_essays(open(path, encoding="utf-8").read())


def main(path):
    bodies = load_bodies(path)
    # ── детектор 1: коинажи (как раньше) ──
    seen, coin = set(), []
    for name, body in sorted(bodies.items()):
        if name == "poker-glossary":
            continue
        for w in re.findall(r"[а-яёА-ЯЁ]{%d,}" % MIN_LEN, body):
            wl = w.lower()
            if wl in seen or zipf(wl) > ZERO_THRESHOLD:
                continue
            nwl = _norm(wl)
            if nwl in SURFACE_ALLOW:
                continue
            if _norm(lemma(wl)) in ALLOWLIST_N or nwl in ALLOWLIST_N:
                continue
            if any(nwl.startswith(st) for st in NAME_STEMS):
                continue
            if is_proper(wl) or is_merge(w):
                continue
            seen.add(wl)
            coin.append((name, w, context(body, w)))
    # ── детекторы 2 и 3 ──
    mixed, stop = [], []
    for name, body in sorted(bodies.items()):
        mixed += scan_mixed(name, body)
        stop += scan_stop(name, body)

    def dump(title, rows):
        print(f"\n# {title}: {len(rows)}")
        print("slug\tметка\tконтекст")
        for r in rows:
            print("%s\t%s\t%s" % r)

    dump("[1] коинажи (zipf=0, не имя/жаргон/склейка)", coin)
    dump("[2] латинско-кириллические склейки", mixed)
    dump("[3] стоп-лист (забракованные слова, с исключениями)", stop)
    sys.exit(1 if (coin or mixed or stop) else 0)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "audit/all-prose.md")
